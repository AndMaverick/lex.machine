def to_python(text: str) -> str:
    """Rewrite a control expression as Python source: dotted paths become plain names, true/false become True/False."""
    out = re.sub(r"\b(?:system|evidence)(?:\.[A-Za-z_][A-Za-z0-9_]*)+", lambda m: m.group(0).replace(".", "__"), text)
    out = re.sub(r"\btrue\b", "True", out)
    return re.sub(r"\bfalse\b", "False", out)


def py_eval(text: str, env: dict[str, object]) -> object:
    """Evaluate with Python itself. Only for expressions generated by the tests."""
    return eval(to_python(text), {"__builtins__": {}}, {k.replace(".", "__"): v for k, v in env.items()})  # noqa: S307


def random_expression(rng: random.Random, names: list[str], depth: int = 3) -> str:
    """A random boolean expression over numeric variables, comparisons, and, or, not and parentheses."""
    if depth == 0 or rng.random() < 0.25:
        v = rng.choice(names)
        op = rng.choice(["<", "<=", ">", ">=", "==", "!="])
        return f"{v} {op} {rng.randint(0, 3)}"
    kind = rng.choice(["and", "or", "not", "in"])
    if kind == "not":
        return f"not ({random_expression(rng, names, depth - 1)})"
    if kind == "in":
        items = ", ".join(str(x) for x in rng.sample(range(0, 4), rng.randint(1, 3)))
        return f"{rng.choice(names)} in [{items}]"
    return f"({random_expression(rng, names, depth - 1)} {kind} {random_expression(rng, names, depth - 1)})"


def completions(names: list[str], domain: list[int]):
    for combo in itertools.product(domain, repeat=len(names)):
        yield dict(zip(names, combo, strict=True))


def wilson_bounds(k: int, n: int, z: float) -> tuple[float, float]:
    """The Wilson interval from its definition: the proportions p whose own standard error puts k/n within z of p. Found by bisection."""
    phat = k / n

    def inside(p: float) -> bool:
        return abs(phat - p) <= z * math.sqrt(p * (1 - p) / n) + 1e-15

    def edge(lo: float, hi: float, want_inside_at_lo: bool) -> float:
        for _ in range(200):
            mid = (lo + hi) / 2
            if inside(mid) == want_inside_at_lo:
                lo = mid
            else:
                hi = mid
        return (lo + hi) / 2

    return (0.0 if k == 0 else edge(0.0, phat, False) if not inside(0.0) else 0.0,
            1.0 if k == n else edge(phat, 1.0, True))


def fisher_by_enumeration(k1: int, n1: int, k2: int, n2: int) -> Fraction:
    """Two-sided Fisher exact p by listing every way to place the K successes among the N units (small tables only)."""
    total, big_k = n1 + n2, k1 + k2
    counts: Counter[int] = Counter()
    for placed in itertools.combinations(range(total), big_k):
        counts[sum(1 for i in placed if i < n1)] += 1
    every = sum(counts.values())
    return Fraction(sum(c for c in counts.values() if c <= counts[k1]), every)


def age_days(collected: str, as_of: str) -> int:
    return (datetime.date.fromisoformat(as_of) - datetime.date.fromisoformat(collected)).days


def weighted_readiness(rows: list[tuple[str, str]]) -> Fraction:
    """rows of (severity, status); critical 5, major 3, minor 1; not_applicable excluded."""
    w = {"critical": 5, "major": 3, "minor": 1}
    den = sum(w[s] for s, st in rows if st != "not_applicable")
    num = sum(w[s] for s, st in rows if st == "satisfied")
    return Fraction(num, den) if den else Fraction(0)


def history_hash(prev: str, attestation: dict) -> str:
    body = json.dumps(attestation, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(f"{prev}\n{body}".encode("ascii")).hexdigest()


def file_digest(path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()
